let language = localStorage.getItem("altium-migration-language") || "fr";
if (!messages[language]) language = "fr";

export function t(key, variables = {}) {
  let value = messages[language]?.[key] || messages.fr[key] || key;
  for (const [name, replacement] of Object.entries(variables)) value = value.replaceAll(`{${name}}`, replacement);
  return value;
}

export function getLanguage() { return language; }

export function setLanguage(nextLanguage) {
  if (!messages[nextLanguage]) return;
  language = nextLanguage;
  localStorage.setItem("altium-migration-language", language);
  document.documentElement.lang = language;
}

export function translateDocument() {
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => { element.textContent = t(element.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => { element.placeholder = t(element.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-title]").forEach((element) => { element.title = t(element.dataset.i18nTitle); });
}
